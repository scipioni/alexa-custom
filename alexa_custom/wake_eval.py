"""Wake-word detection evaluation harness.

Scores stage-1 wake detection against labelled audio corpora offline —
no microphone, no PortAudio, no parec subprocess. Feeds 16 kHz mono
s16le WAV clips through the same Vosk/KWS decision helpers used in
production and reports false-positives-per-hour and miss-rate.

CLI: ``alexa-wake-eval --help``

Corpus layout
-------------
eval/corpus/
    positive/        clips that SHOULD trigger a wake
        clip_001.wav
        ...
    negative/        clips that must NOT trigger a wake
        clip_001.wav
        ...
    manifest.yaml    provenance metadata (auto-generated by ``--gen-corpus``)

Each WAV must be 16 kHz, mono, 16-bit PCM (s16le).  The harness converts
via ffmpeg when it finds files in other formats (requires ffmpeg on PATH).
"""

