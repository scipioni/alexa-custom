@dataclass
class ClipResult:
    file: str
    label: str  # "positive" | "negative"
    text: str
    attenuation_db: float
    woke: bool
    duration_s: float = 0.0


@dataclass
class EvalResult:
    clips: list[ClipResult] = field(default_factory=list)
    total_negative_s: float = 0.0

    @property
    def false_positives(self) -> int:
        return sum(1 for c in self.clips if c.label == "negative" and c.woke)

    @property
    def true_negatives(self) -> int:
        return sum(1 for c in self.clips if c.label == "negative" and not c.woke)

    @property
    def misses(self) -> int:
        return sum(1 for c in self.clips if c.label == "positive" and not c.woke)

    @property
    def true_positives(self) -> int:
        return sum(1 for c in self.clips if c.label == "positive" and c.woke)

    @property
    def fp_per_hour(self) -> float:
        if self.total_negative_s == 0:
            return float("inf")
        return self.false_positives / (self.total_negative_s / 3600.0)

    @property
    def miss_rate(self) -> float:
        total_pos = self.true_positives + self.misses
        if total_pos == 0:
            return 0.0
        return self.misses / total_pos


def run_eval(
    corpus_dir: Path, ec: EvalConfig, wake_word_strs: list[str] | None = None
) -> EvalResult:
    """Score the corpus at ``corpus_dir`` against the given eval config.

    ``wake_word_strs`` overrides the wake words from ``ec`` if provided.
    """

    ww_strs = wake_word_strs or ec.wake_words
    wake_words = [WakeWordGroup(word=w) for w in ww_strs]
    stage1_cfg = _make_stage1_config(ec)
    alias_map = _build_alias_map(wake_words)

    # Load Vosk model and build grammar recognizer
    model_path = ec.vosk_model_path
    if not Path(model_path).exists():
        raise FileNotFoundError(f"Vosk model not found at {model_path}")
    vosk.SetLogLevel(-1)
    vosk_model = vosk.Model(model_path)
    # Match the production recognizer vocabulary: free-text, the exact loop
    # grammar from the live config, or (legacy) a wake-words-only grammar.
    if ec.free_text:
        grammar = None
    elif ec.grammar is not None:
        grammar = ec.grammar
    else:
        grammar = _grammar_json(wake_words)

    manifest = load_manifest(corpus_dir)
    result = EvalResult()

    for label in ("positive", "negative"):
        entries = manifest.get(label, [])
        for entry in entries:
            clip_path = corpus_dir / entry["file"]
            if not clip_path.exists():
                logger.warning("Clip not found: %s — skipping", clip_path)
                continue
            try:
                pcm = _read_wav_pcm(clip_path)
                dur = _wav_duration_s(clip_path)
            except Exception as e:
                logger.warning("Could not read %s: %s", clip_path, e)
                continue

            # Fresh recognizer per clip so state doesn't bleed between clips
            recognizer = (
                vosk.KaldiRecognizer(vosk_model, 16000, grammar)
                if grammar
                else vosk.KaldiRecognizer(vosk_model, 16000)
            )
            recognizer.SetWords(True)

            woke = _score_clip_vosk(pcm, recognizer, alias_map, stage1_cfg)

            clip_result = ClipResult(
                file=entry["file"],
                label=label,
                text=entry.get("text", ""),
                attenuation_db=entry.get("attenuation_db", 0),
                woke=woke,
                duration_s=dur,
            )
            result.clips.append(clip_result)
            if label == "negative":
                result.total_negative_s += dur

            status = "WAKE" if woke else "---"
            expected = "WAKE" if label == "positive" else "---"
            ok = "✓" if status == expected else "✗"
            logger.info(
                "%s [%s] %s %r (%.1f dB)",
                ok,
                label.upper()[:3],
                status,
                entry.get("text", ""),
                entry.get("attenuation_db", 0),
            )

    return result


