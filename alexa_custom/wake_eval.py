def save_baseline(path: Path, ec: EvalConfig, result: EvalResult) -> None:
    data = {
        "confidence": ec.confidence,
        "confidence_mode": ec.confidence_mode,
        "rms_threshold": ec.rms_threshold,
        "wake_match_threshold": ec.wake_match_threshold,
        "fp_per_hour": result.fp_per_hour,
        "miss_rate": result.miss_rate,
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w") as f:
        yaml.dump(data, f)
    print(f"Baseline saved to {path}")


def check_baseline(path: Path, result: EvalResult) -> bool:
    """Return True if result is within baseline, False (regression) otherwise."""
    if not path.exists():
        print(f"No baseline at {path} — run with --save-baseline first.")
        return True
    with open(path) as f:
        baseline = yaml.safe_load(f)
    ok = True
    fp_base = baseline.get("fp_per_hour", float("inf"))
    miss_base = baseline.get("miss_rate", 1.0)
    if result.fp_per_hour > fp_base * 1.2 + 0.1:
        print(f"REGRESSION: FP/hour {result.fp_per_hour:.2f} > baseline {fp_base:.2f}")
        ok = False
    if result.miss_rate > miss_base + 0.05:
        print(
            f"REGRESSION: miss_rate {result.miss_rate:.1%} > baseline {miss_base:.1%}"
        )
        ok = False
    if ok:
        print(
            f"OK: within baseline (FP/hr {result.fp_per_hour:.2f}, miss {result.miss_rate:.1%})"
        )
    return ok


