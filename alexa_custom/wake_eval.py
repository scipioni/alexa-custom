def _read_wav_pcm(path: Path) -> bytes:
    """Return raw s16le 16 kHz mono bytes from a WAV file.

    Converts via ffmpeg if the file is not already in the required format.
    """
    if _FFMPEG:
        result = subprocess.run(
            [
                _FFMPEG,
                "-y",
                "-i",
                str(path),
                "-ar",
                "16000",
                "-ac",
                "1",
                "-f",
                "s16le",
                "pipe:1",
            ],
            capture_output=True,
            check=True,
        )
        # Append 0.5 s of silence so the endpoint detector fires after speech
        silence = bytes(int(16000 * 0.5) * 2)
        return result.stdout + silence
    # Fallback: read WAV directly (must already be 16 kHz mono s16le)
    with wave.open(str(path), "rb") as wf:
        return wf.readframes(wf.getnframes())


def _wav_duration_s(path: Path) -> float:
    """Return the duration of a WAV file in seconds (without loading all samples)."""
    with wave.open(str(path), "rb") as wf:
        return wf.getnframes() / wf.getframerate()


