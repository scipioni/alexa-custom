def print_report(ec: EvalConfig, result: EvalResult, label: str = "") -> None:
    header = f"=== Eval Report{': ' + label if label else ''} ==="
    print(header)
    print(
        f"  confidence={ec.confidence}  mode={ec.confidence_mode}  "
        f"rms_threshold={ec.rms_threshold}  wake_match_threshold={ec.wake_match_threshold}"
    )
    print()
    print(f"  Positive clips : {result.true_positives + result.misses}")
    print(f"    detected     : {result.true_positives}")
    print(f"    missed       : {result.misses}")
    print(f"  Miss rate      : {result.miss_rate:.1%}")
    print()
    print(f"  Negative clips : {result.true_negatives + result.false_positives}")
    print(f"    false wakes  : {result.false_positives}")
    print(f"  Neg audio dur  : {result.total_negative_s:.1f} s")
    print(f"  FP / hour      : {result.fp_per_hour:.2f}")
    if result.false_positives:
        print()
        print("  False-positive clips:")
        for c in result.clips:
            if c.label == "negative" and c.woke:
                print(f"    {c.file}  ({c.text!r}, {c.attenuation_db} dB)")
    print("=" * len(header))


def print_sweep_table(rows: list[tuple[EvalConfig, EvalResult, str]]) -> None:
    print()
    print(f"{'Config':<50}  {'FP/hr':>7}  {'Miss%':>7}  {'FPs':>4}  {'Misses':>6}")
    print("-" * 80)
    for ec, res, label in rows:
        name = label or (
            f"conf={ec.confidence} mode={ec.confidence_mode} "
            f"rms={ec.rms_threshold} wmt={ec.wake_match_threshold}"
        )
        fp_h = f"{res.fp_per_hour:.2f}" if res.total_negative_s > 0 else "N/A"
        miss = f"{res.miss_rate:.1%}"
        print(
            f"{name:<50}  {fp_h:>7}  {miss:>7}  {res.false_positives:>4}  {res.misses:>6}"
        )
    print()


